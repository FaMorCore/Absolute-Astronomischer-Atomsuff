_UNKNOWN = [
    "?????",
    "?????",
    "?????",
    "?????",
    "?????",
]


def render(text: str) -> str:
    """Wandelt eine (ggf. mehrzeilige) Eingabe in mehrzeilige ASCII-Art um.

    Jede Textzeile ergibt einen ASCII-Art-Block; Zeilenumbrueche bleiben erhalten.
    """
    out_lines = []
    text_lines = text.replace("\r\n", "\n").split("\n")

    for t, raw_line in enumerate(text_lines):
        line = raw_line.upper()
        rows = ["" for _ in range(HEIGHT)]

        for ch in line:
            glyph = GLYPHS.get(ch, _UNKNOWN)
            for r in range(HEIGHT):
                rows[r] += glyph[r] + " "

        for r in range(HEIGHT):
            out_lines.append(rows[r].rstrip())

        if t < len(text_lines) - 1:
            out_lines.append("")

    return "\n".join(out_lines).rstrip("\n")
